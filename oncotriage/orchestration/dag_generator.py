# Create DAG
############

"""Generate the ``trial_refresh_weekly`` Airflow DAG and write it to disk.

Moved out of "23- Airflow DAG.py" by item 20c, pass 3c-2. That file is now a
thin entry point: a ``__main__`` guard and one call.

THE OUTPUT OF THIS MODULE IS THE ARTEFACT, NOT THIS MODULE
-----------------------------------------------------------
The scheduler parses ``{airflow_path}/dags/trial_refresh_weekly.py``. It never
sees this file. So the only thing that matters about this move is that the
generated TEXT is unchanged, and pass 3c-2 proved that by generating from git
HEAD's File 23 into one temporary directory, generating from this module into
another, and comparing sha256. They match: the DAG text is byte-identical.

THE TWO STALE PROSE LINES ARE FIXED (pass 20f-3), AND THE ACCEPTANCE CRITERION
IS THE OPPOSITE ONE. The generated text used to say "03- Config.py" in two
places -- the DAG module docstring's Schedule line and the comment above
DAG_SCHEDULE -- while the code beneath both of them opened
``oncotriage/config.py``, which is what item 20c retargeted them to. Pass 3c-2
left them wrong on purpose: correcting a character would have changed the bytes
and made ITS equivalence proof meaningless, so it recorded a one-line follow-up
"whose acceptance criterion is a NEW sha256". Pass 20e then DELETED
``03- Config.py`` outright, so the generated DAG named a file that does not
exist -- prose pointing an operator at nothing.

So this pass had to produce a new sha256, and did: the deployed DAG went from
20,542 bytes / ``68963b0c...`` to the size and digest recorded in CLAUDE.md,
regenerated by deleting the file and re-running "23- Airflow DAG.py", and
Airflow's own ``DagBag`` was asked to parse the result rather than the parse
being assumed.

WHY dag_content IS A FUNCTION NOW
---------------------------------
File 23 assembled ``dag_content`` at MODULE LEVEL, and the middle third of it is
``%``-formatted with three resolved paths -- ``code_path``, ``keys_path`` and
``data_trial_path``. Reading any of those fires ``oncotriage.paths``' lazy
resolver, which globs the sibling directory tree. So importing this module, had
the assembly stayed at module level, would have resolved three directories and
raised on any machine without them. ``build_dag_content()`` is the fix; the head
and the tail stay module-level constants because they are plain strings that
resolve nothing.

Note which half of File 23's item-20b comment survives that. It said "dag_content
itself stays at module level -- it is a string, building it touches nothing".
The first clause was right and the second was not: building it read three lazy
paths. Under the exec chain that was invisible, because "01- Imports.py" had
already resolved every path before File 23 was reached.

WHAT IMPORTING THIS MODULE DOES
-------------------------------
Binds three string constants and four functions. It resolves no path, reads no
file, creates no directory and writes nothing. ``oncotriage.paths`` and
``oncotriage.settings`` are imported as MODULES -- a ``from X import name``
against ``paths`` is an attribute read and would fire the lazy resolver at
import.

THE DAG NO LONGER DUPLICATES THE SCRAPE OR THE INDEX BUILD
----------------------------------------------------------
It used to, and the previous version of this paragraph recorded that as "a
known cost rather than a discovery" and deferred the fix. The cost came due:
the copies HAD drifted, in every direction at once, and the generated DAG
built a materially worse index than ``11- RAG Trial Indexer.py`` -- no sparse
vectors at all, no payload index, no conditionsModule, a splitter whose
inclusion marker ``"patients must"`` is a prefix of its own exclusion marker
``"patients must not"``, one embedding API call per trial, the same exactly-18
age filter, and a verify step that ran after the alias swap.

The generated tasks now call ``oncotriage.retrieval.indexer`` directly. The
import is DEFERRED INTO EACH TASK -- never at module scope -- so the
scheduler's continuous re-parse of the dags folder cannot be broken by an
environment that lacks the package; only an actual run fails, and it fails
naming the path it tried. That is the trade the old copies were avoiding, and
it is the right one: a DAG that will not run is visible, a DAG that runs and
promotes a sparse-vector-less collection is not.
"""

