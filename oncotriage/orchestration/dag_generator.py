# Write DAG file
# Item 20b: creating the dags/ directory and writing the file were both module
# level, so loading this file wrote to disk.
def write_dag_file(dags_root, content=None):
    """Write the generated DAG under dags_root, unless a different one is there.

    Args:
        dags_root: The AIRFLOW_HOME. The file lands at ``dags_root/dags/``.
        content:   The DAG text. None calls ``build_dag_content()``, which is
                   what File 23's module-level ``dag_content`` supplied. Passing
                   it explicitly lets a caller write text it built with
                   overridden paths, without a second resolution.

    Returns the destination path. Refuses to overwrite a file whose text
    differs from the generated content, in case it was edited in place.
    """
    if content is None:
        content = build_dag_content()

    dag_dir = Path(dags_root) / 'dags'
    dag_dir.mkdir(parents=True, exist_ok=True)
    dag_file = dag_dir / 'trial_refresh_weekly.py'

    # If it exists
    if dag_file.exists():
        if dag_file.read_text() == content:
            console.out(f"✓ DAG file already exists and matches this generator: {dag_file}")
        else:
            console.out(f"! DAG file already exists and DIFFERS from this generator: {dag_file}")
            console.out("  Not overwriting, in case it was edited in place.")
            console.out("  The scheduler parses that file, not the string in this one, so every")
            console.out("  edit made here -- including the schedule -- is inert until it is replaced.")
            console.out("  Delete it and re-run this file to regenerate.")
    else:
        dag_file.write_text(content)
        console.out(f"✓ New DAG file created: {dag_file}")

    return dag_file


def write_dag_file_to_default(content=None):
    """Write the DAG under the resolved AIRFLOW_HOME.

    The one call File 23's ``__main__`` block made, with the path resolved here
    rather than read out of the exec namespace. Kept separate from
    ``write_dag_file`` so that the writer itself never resolves a directory --
    a caller who names its own destination resolves nothing at all.
    """
    return write_dag_file(resolve_airflow_home(), content=content)


