_RESULTS = {"passed": 0, "failed": 0}
_FAILURES = []


def check(label: str, actual, expected) -> None:
    """Assert equality, record the outcome, never abort the run."""
    if actual == expected:
        _RESULTS["passed"] += 1
        print(f"  PASS  {label}")
    else:
        _RESULTS["failed"] += 1
        _FAILURES.append(
            f"{label}\n          expected: {expected}\n          actual:   {actual}"
        )
        print(f"  FAIL  {label}")
        print(f"          expected: {expected}")
        print(f"          actual:   {actual}")


def check_raises(label: str, fn, exc_type=ValueError):
    """Pass if fn() raises exc_type; fail if it returns or raises anything else.

    "Refused the value" is the assertion here, not a side effect of one: the
    defect being guarded against is a bad grade being quietly rounded or
    defaulted into the record.
    """
    try:
        value = fn()
    except exc_type as exc:
        _RESULTS["passed"] += 1
        print(f"  PASS  {label}  ({type(exc).__name__})")
        return exc
    except Exception as exc:
        _RESULTS["failed"] += 1
        _FAILURES.append(
            f"{label}\n          expected {exc_type.__name__}, "
            f"raised {type(exc).__name__}: {exc}"
        )
        print(f"  FAIL  {label}  (raised {type(exc).__name__}: {exc})")
        return None
    _RESULTS["failed"] += 1
    _FAILURES.append(f"{label}\n          did not raise; returned {value!r}")
    print(f"  FAIL  {label}  (did not raise; returned {value!r})")
    return None


def _ecog_resource(value_block: dict, date: str = "2020-06-28T13:49:49-07:00") -> dict:
    """A minimal but realistic ECOG Observation, shaped like Synthea's export."""
    resource = {
        "resourceType": "Observation",
        "status": "final",
        "category": [{"coding": [{
            "system": "http://terminology.hl7.org/CodeSystem/observation-category",
            "code": "survey", "display": "Survey"}]}],
        "code": {"coding": [{
            "system": "http://loinc.org",
            "code": "89247-1",
            "display": "ECOG Performance Status score"}]},
        "subject": {"reference": "urn:uuid:patient"},
        "encounter": {"reference": "urn:uuid:encounter"},
    }
    if date is not None:
        resource["effectiveDateTime"] = date
    resource.update(value_block)
    return resource


