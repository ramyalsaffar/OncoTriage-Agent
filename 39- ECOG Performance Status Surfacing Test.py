"""
ECOG Performance Status Surfacing Test

Covers routing LOINC 89247-1 out of the general observation pool and into a
first-class field that reaches GPT-4o.

The defect: File 07 sent every observation that was not an mCODE stage group or
genomic variant into patient_data['observations']. ECOG landed there and then
died there. OncologyLabRegistry does not carry 89247-1, so the summary's lab
section never showed it; "ECOG Performance Status score" matches no biomarker
keyword, so that section never showed it either. The score was parsed and
silently dropped before the prompt was built -- and ECOG 0-1 or 0-2 is the
single most common gate in interventional oncology, so every one of those
criteria came back not_evaluable for every patient.

Covers:
    1. _parse_ecog_observation reads BOTH value shapes -- valueInteger (the
       mCODE form written by File 04's normalizer) and valueQuantity (what
       Synthea's exporter actually emits, with UCUM "{score}") -- and records
       which one it found.
    2. It RAISES on a non-integral value, an out-of-range grade, an absent
       value[x], and an unreadable value[x] shape. Rounding 1.5 to 2 would
       invent a grade the record does not contain.
    3. _select_ecog_performance_status takes the most recent observation dated
       on or before get_age_reference_date() -- never datetime.now() -- and
       records how many were found, how they partitioned, and which path
       produced the answer.
    4. Absence is distinct from a score of 0, in the field, in the hash, and in
       the prompt text. ECOG 0 is FULLY ACTIVE: the most eligible a patient can
       be, and exactly the value a truthiness test would erase.
    5. compute_patient_hash (File 13) includes ECOG, so its docstring promise --
       identical hash means identical input -- still holds once patients carry
       a score. A bundle with no ECOG hashes exactly as it did before the field
       existed, so already-logged hashes stay comparable.
    6. _create_patient_summary emits a named Performance Status line.
    7. END TO END on the scratch corpus generated by '04- FHIR Generate Data.py'
       (item: Generate ECOG performance status in Synthea): real bundles are
       parsed, the field is populated, 89247-1 never appears in the general
       observation pool, and _create_patient_summary is called directly on the
       parsed patients.
    8. STRUCTURAL -- _create_patient_summary touches neither the OpenAI client
       nor the Qdrant client, so section 7 proves the summary text without a
       single network call.

No network and no LLM. File 13 is loaded (its registries are local files and
its BM25 model is a local FastEmbed cache), but no OpenAI or Qdrant call is
made: the only File 13 functions invoked are compute_patient_hash and
_create_patient_summary, both pure.

Run from terminal (or F5 in Spyder):
    python "39- ECOG Performance Status Surfacing Test.py"

Exit codes:
    0 -- all assertions passed
    1 -- one or more failures
"""


